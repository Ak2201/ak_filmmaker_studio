#!/usr/bin/env node
/* ============================================================
   make-plan-features-sql — schema section 35, GENERATED from
   src/data/plan-matrix.json through src/lib/plan-matrix.js
   ------------------------------------------------------------
     node scripts/make-plan-features-sql.mjs           print §35
     node scripts/make-plan-features-sql.mjs --write   put it in supabase-schema.sql
     node scripts/make-plan-features-sql.mjs --check   exit 1 if the file differs

   The section is everything from its header line to the end of the
   file (§35 is the last section; a §36 would start after END_MARK).
   `npm run test:plans` runs --check, so the matrix and the SQL the
   owner runs cannot drift: edit the JSON, run --write, commit both.
   ============================================================ */
import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('../', import.meta.url);
const SCHEMA = new URL('supabase-schema.sql', ROOT);
export const HEAD_MARK = '-- 35. PLAN FEATURES FROM THE MATRIX';
export const END_MARK = '-- END OF SECTION 35 (generated)';

/** plan-matrix.js, loaded in Node with its two JSON imports inlined. */
export async function loadMatrixModule() {
  const json = (p) => readFileSync(new URL(p, ROOT), 'utf8');
  const src = readFileSync(new URL('src/lib/plan-matrix.js', ROOT), 'utf8')
    .replace("import matrix from '../data/plan-matrix.json';", 'const matrix = ' + json('src/data/plan-matrix.json') + ';')
    .replace("import nav from '../data/navigation.json';", 'const nav = ' + json('src/data/navigation.json') + ';');
  return import('data:text/javascript,' + encodeURIComponent(src));
}

const lit = (obj) => "'" + JSON.stringify(obj).replace(/'/g, "''") + "'::jsonb";

export async function generate() {
  const M = await loadMatrixModule();
  const lines = [];
  const L = (s = '') => lines.push(s);
  L('-- ============================================================');
  L(HEAD_MARK + '   RUN LIVE: not yet');
  L('-- ------------------------------------------------------------');
  L('-- GENERATED by scripts/make-plan-features-sql.mjs from');
  L('-- src/data/plan-matrix.json. Do not edit by hand: change the JSON, run');
  L('-- `node scripts/make-plan-features-sql.mjs --write`, commit both.');
  L('-- `npm run test:plans` fails when this text is not what the script prints.');
  L('--');
  L('-- The owner\'s decision, 11 Oct 2026: three plans, each including');
  L('-- everything below it, and the matrix REPLACES the live features map');
  L('-- (the console can fine-tune it afterwards):');
  for (const id of M.PAID) {
    const added = M.addedBy(id).map(M.labelOf);
    const head = '--   ' + M.MATRIX.plans[id] + (id === M.PAID[0] ? ': ' : ' adds: ');
    let cur = head;
    for (const [i, w] of added.entries()) {
      const piece = w + (i < added.length - 1 ? ', ' : '.');
      if ((cur + piece).length > 74) { L(cur.trimEnd()); cur = '--       '; }
      cur += piece;
    }
    L(cur.trimEnd());
  }
  L('--');
  L('-- WHAT IT WRITES. plans.features for each paid plan, replaced whole —');
  L('-- every module id in navigation.json and every capability, explicitly');
  L('-- true or false, the shape the console\'s SAVE writes (sample_only is a');
  L('-- restriction and is present only where it applies, so a paid map');
  L('-- carries none). And limits.extension, merged into the plan\'s limits so');
  L('-- the caps the console set are kept. The \'free\' row is NOT touched: it');
  L('-- is the trial / no-plan state, seeded by section 18, never sold.');
  L('--');
  L('-- WHAT READS IT. billing_status() carries the map (section 33.2); while');
  L('-- purchases are not required, or for a plan-less e-mail grant, it is');
  L('-- open_features() (section 32.3) — the top paid plan\'s map, which is');
  L('-- now Pro\'s: everything. plan-gate.js reads a missing key as allowed');
  L('-- and false as locked; nothing here is a security boundary (RLS and the');
  L('-- P0402 triggers are).');
  L('--');
  L('-- IDEMPOTENT: plain updates by id; a re-run writes the same values.');
  L('-- ============================================================');
  L();
  for (const id of M.PAID) {
    L(`update public.plans set features = ${lit(M.matrixFeatures(id))}`);
    L(`  where id = '${id}';`);
    L(`update public.plans set limits = coalesce(limits, '{}'::jsonb) || ${lit(M.matrixLimits(id))}`);
    L(`  where id = '${id}';`);
  }
  L();
  L("notify pgrst, 'reload schema';");
  L();
  L('-- 35.1 CHECKS TO RUN, none of which has been run live -------------------');
  L('--  1. select id, features from plans: starter / indie / pro carry exactly');
  L('--     matrixFeatures(id) from src/lib/plan-matrix.js; free is unchanged.');
  L('--  2. billing_status() for a Basic, an Intermediate and a Pro buyer, with');
  L('--     purchases required -> features = that plan\'s map.');
  L('--  3. purchases not required, or a plan-less e-mail grant ->');
  L('--     billing_status().features = open_features() = Pro\'s map.');
  L('--  4. limits.extension: false on starter, true on indie and pro; the');
  L('--     other caps are what they were.');
  L('--  5. re-running the section changes nothing.');
  L('-- Test file: scripts/schema-tests/plan-features.sql (run by npm run test:schema).');
  L(END_MARK);
  L('-- ============================================================');
  return lines.join('\n') + '\n';
}

/** The §35 text currently in supabase-schema.sql, or null. */
export function current(text) {
  const at = text.indexOf(HEAD_MARK);
  if (at < 0) return null;
  const start = text.lastIndexOf('-- ====', at);
  const endAt = text.indexOf(END_MARK, at);
  if (endAt < 0) return null;
  const close = text.indexOf('\n', text.indexOf('\n', endAt) + 1);
  return { start, end: close < 0 ? text.length : close + 1, body: text.slice(start, close < 0 ? text.length : close + 1) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const want = await generate();
  const text = readFileSync(SCHEMA, 'utf8');
  const cur = current(text);
  if (process.argv.includes('--check')) {
    if (!cur || cur.body !== want) {
      console.error('✗ supabase-schema.sql §35 is not what scripts/make-plan-features-sql.mjs generates from plan-matrix.json — run it with --write');
      process.exit(1);
    }
    console.log('✓ §35 matches plan-matrix.json');
  } else if (process.argv.includes('--write')) {
    const next = cur ? text.slice(0, cur.start) + want + text.slice(cur.end) : text.replace(/\n*$/, '\n\n') + want;
    writeFileSync(SCHEMA, next);
    console.log(cur ? 'replaced §35' : 'appended §35');
  } else {
    process.stdout.write(want);
  }
}
