/* ============================================================
   TEST — script import: what the scene rows come out as, PINNED
   ------------------------------------------------------------
   src/lib/script-import.js in Node, no browser:

       node scripts/test-import.mjs   (or: npm run test:import)

   WHY THIS FILE EXISTS. docs/KNOWN-ISSUES.md §6: the importer had its
   own scene slicer (`sliceScenes`) beside the one every other module
   reads (`sliceScript` in src/lib/screenplay-analysis.js), and the two
   were not byte-identical on RAW element arrays — the shared one trims
   the heading and drops empty elements (an empty heading included),
   the importer's kept both. Folding them could only be allowed with a
   test that pins what an import PRODUCES first. This is that test.

   The fixtures are chosen for exactly the inputs where the two could
   have disagreed: blank lines, trailing whitespace, a preamble above
   the first heading, a heading followed at once by another (an empty
   scene), a heading paragraph with no text at all (.fdx), a heading
   with inner runs of spaces, and a numbered heading. The expected rows
   below were captured from the importer BEFORE the merge and are not
   regenerated by the test — change them only on purpose.

   The second half asserts the reason the merge is safe: every parser
   already emits trimmed, non-empty text, so the slicer never sees the
   inputs the two implementations differed on. Should a parser ever
   start emitting an empty or untrimmed element, that assertion is the
   one that fails, and it fails before any row does.
   ============================================================ */
