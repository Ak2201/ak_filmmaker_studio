/* ============================================================
   JOURNEY — where the open film is, across the five stages
   ------------------------------------------------------------
   One derivation, read by the hub's journey strip, the dashboard and
   the project cards. It STORES NOTHING and must stay that way: every
   answer is computed at render time from the models that already own
   the facts, for the reason readiness.js gives — a cached "current
   stage" is a second copy of an answer that is wrong the first time
   either copy is edited, and a dashboard that writes on load trips
   verify's idle-write check.

   TWO MEASURES PER STAGE, because the studio has two ways of doing
   the same work and a writer may use either, both, or neither:

     guide   the blueprint's steps for that stage — feature.html or
             short.html — counted with the blueprint's own rule for
             "filled" (blueprint-fields.js: a non-empty string or a
             ticked item). A step is COMPLETE when every field it
             declares is filled, which is the rule the blueprint's
             own step badges use ("✓ COMPLETE" at 100%).
     tools   the stage's real modules, asked a few yes/no questions
             each, from the models:
               story       fms_story_v1: logline, outline, synopsis,
                           tagged passages            (story.js)
               screenplay  the script and the scene list
                           (script.js, scenes.js)
               preprod     every readiness() check   (readiness.js)
               production  scenes marked shot        (shootday.js)
               post        scenes in the cut and the deliverables
                           list                      (editlog.js,
                           deliverables.js)

   WHICH STEP BELONGS TO WHICH STAGE. src/data/steps.stages.json is
   the sidecar that owns this (the step files are regenerated by
   `npm run extract`, so the fact cannot live in them). When it is
   present it wins; the table below is the fallback that matches the
   approved plan, so this file works in a checkout without it:

     feature  01–10 story · 11–13 screenplay · 14–24 preprod ·
              25–28 production · 29–32 post
     short    1–5 story · 6–8 screenplay · 9 preprod · 10–11 post
              (step 9 "Production Reality" is the short's planning
              step — a schedule, a budget, a crew — so it sits under
              Pre-Production and the short has no production step)

   "CURRENT" — the earliest stage that is not substantially done.
   The heuristic, in full:

     guideOK  the stage has no guide steps, or ≥ 80% of its guide
              FIELDS are filled
     toolsOK  ≥ 75% of the stage's tool checks pass (a stage whose
              tools have nothing to measure yet — production with no
              scenes — is NOT ok: zero of zero is not done)
     done     toolsOK && (guideOK || work has started in a later
              stage's tools)

   The last clause is what keeps the guide optional. The tools are the
   work; the blueprint is a companion. Somebody who has a script, a
   schedule and shots logged but never opened the blueprint is not
   "in Story", and somebody who has filled every step of Part I but
   has no logline in the Story module has not finished the story
   either. When every stage is done, current is the last one and
   `complete` is true.

   "NEXT" — one action for the current stage. A failing tool check
   first (the work), then the first incomplete guide step of that
   stage (the companion). Hrefs point into the module or the
   blueprint step that owns the gap.
   ============================================================ */
