/* ============================================================
   COMPANY — contact.html and about.html's only script
   ------------------------------------------------------------
   Both pages are generated by scripts/make-marketing-pages.mjs and keep
   their words in the markup. They sit OUTSIDE the site gate, like the
   product pages, and load what those load (marketing.js: the header, the
   mega-menu, the sign-up modal behind "Start your free trial") plus the
   one thing only contact.html does:

   THE CONTACT FORM SENDS NOTHING. It is validated here, with the errors
   written beside each field (aria-invalid + aria-describedby) and a
   summary that takes focus, and then turned into a mailto: link to the
   support address printed on the page. The visitor's own mail app does
   the sending; nothing goes to or is stored on any server, and nothing
   is written to storage. The rules and the link are in
   src/lib/contact-model.js (pure, tested by test:contact).

   WHAT IT MAY IMPORT: marketing.js, its own sheet and pure leaf
   libraries, never the studio CORE (the startlib rule, test:marketing).
   ============================================================ */
import './marketing.js';
import '../styles/company.css';
import { validateContact, contactMailto } from '../lib/contact-model.js';

const form = document.getElementById('coForm');
if (form) wireContact(form);

function wireContact(form) {
  const FIELDS = ['name', 'email', 'topic', 'message'];
  const ctl = (k) => form.elements.namedItem(k);
  const errEl = (k) => document.getElementById('co-' + k + '-err');
  const summary = document.getElementById('coSummary');
  const status = document.getElementById('coStatus');
  const topicSel = ctl('topic');
  const topics = topicSel ? Array.from(topicSel.options).map((o) => o.value) : [];
  /* error key -> sentence, from the markup's data-err-* attributes */
  const sentence = (key) => form.dataset['err' + key.charAt(0).toUpperCase() + key.slice(1)] || '';
  let tried = false;

  const values = () => Object.fromEntries(FIELDS.map((k) => [k, ctl(k) ? ctl(k).value : '']));

  function show(bad) {
    for (const k of FIELDS) {
      const c = ctl(k), e = errEl(k);
      if (!c || !e) continue;
      if (bad[k]) {
        c.setAttribute('aria-invalid', 'true');
        e.textContent = sentence(bad[k]);
        e.hidden = false;
      } else {
        c.removeAttribute('aria-invalid');
        e.textContent = '';
        e.hidden = true;
      }
    }
  }

  /* After the first attempt, a field's message follows the typing, so a
     fixed field stops saying it is wrong without another press. */
  form.addEventListener('input', (e) => {
    if (!tried || !e.target || !FIELDS.includes(e.target.name)) return;
    const bad = validateContact(values(), topics);
    show(bad);
    if (!Object.keys(bad).length && summary) summary.hidden = true;
  });

  form.addEventListener('submit', (e) => {
    e.preventDefault();
    tried = true;
    if (status) status.textContent = '';
    const bad = validateContact(values(), topics);
    show(bad);
    const first = FIELDS.find((k) => bad[k]);
    if (first) {
      if (summary) {
        summary.textContent = form.dataset.errSummary || '';
        summary.hidden = false;
      }
      const c = ctl(first);
      if (c && typeof c.focus === 'function') c.focus();
      return;
    }
    if (summary) summary.hidden = true;
    const toEl = document.getElementById('coEmail');
    const to = toEl ? toEl.textContent : '';
    const topicLabel = topicSel && topicSel.selectedOptions[0] ? topicSel.selectedOptions[0].textContent.trim() : '';
    const url = contactMailto({ to, prefix: form.dataset.subject, topicLabel, fields: values() });
    if (status) status.textContent = form.dataset.opened || '';
    window.location.href = url;
  });
}
