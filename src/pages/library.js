/* ============================================================
   BOOT
   ============================================================ */
function render() {
  const app = document.getElementById('app');
  if (!app) return;

  const toolbar = renderToolbar();

  // The toolbar is site chrome, not document content: it sits before
  // <main> so the skip link actually skips it — and mountShell() then
  // moves it into .sh-bar, which is also before <main>, so that stays
  // true after the adoption.
  const main = h('main#main.lib-main.k-page', { role: 'main' });
  main.append(...renderCover());
  main.append(renderFigures());
  main.append(renderContents());
  main.append(renderTeasers());
  SECTIONS.forEach((s, i) => main.append(renderSection(s, i)));
  main.append(renderFinal());

  app.replaceChildren(toolbar, main);

  wireActions(app);
  mountShelf();

  // StudioUI boots before this module renders, so the bits of it
  // that look for page furniture get a second, explicit call.
  try {
    mountShell();
    StudioUI.attachSignInPill(toolbar);
    StudioUI.upgradeThemeButton(toolbar);
    StudioUI.autoAriaLabels();
    // The craft rules and film notes are exactly where a term needs
    // explaining; .section-body is in the tagger's scope.
    StudioUI.wireGlossaryPopovers();
  } catch (e) { /* cloud/chrome extras are optional */ }
  // A shelf tab the plan does not include shows its lock card; the
  // rest of the Library stays open. See plan-gate.js, "the tab lock".
  try { PlanGate.lockTabs(); } catch (e) { /* not gated */ }
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', render);
} else {
  render();
}
