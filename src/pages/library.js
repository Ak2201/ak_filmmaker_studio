/* ---- the 2026 check layer ---------------------------------
   Keyed by section id then by the row's `item` string, because a
   rate row has no id of its own. That makes the join fragile in one
   specific way — rename an item in the base file and its check
   silently stops matching — so nothing is dropped on a miss:
   unmatched checks are collected and rendered under their section
   as their own note. A check that quietly disappears is the same
   class of bug as a CSS variable that is never defined. */
const CHECKS = rateChecksIndex(rateChecks);
const checksFor = CHECKS.checksFor;
const sourceOf = CHECKS.sourceOf;

/** One line of evidence under a rate, or the reason there is none. */
function renderCheck(c) {
  const src = sourceOf(c.source);
  const line = h('div.rate-check', { 'data-confidence': c.confidence }, [
    h('span.rate-check-tag', { text: CONFIDENCE_LABEL[c.confidence] || 'NOTE' })
  ]);
  if (c.raw) line.append(h('span.rate-check-val', { text: c.raw }));
  if (src) {
    line.append(h('span.rate-check-src', {}, [
      h('a', {
        href: src.url, target: '_blank', rel: 'noopener noreferrer',
        text: src.name
      }),
      `, checked ${c.checked}`
    ]));
  } else if (c.checked) {
    line.append(h('span.rate-check-src', { text: `Looked for on ${c.checked}; nothing published found.` }));
  }
  if (c.caveat) line.append(h('span.rate-check-caveat', { text: c.caveat }));
  return line;
}

