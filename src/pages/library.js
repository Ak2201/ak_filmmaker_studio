/* ============================================================
   ACTIONS — one delegated listener, zero inline handlers.
   ============================================================ */
/* The page's own delegated actions. The theme button went in the
   one-frame pass (one theme; the band's tools are the same everywhere),
   so the table is empty, and the dispatcher stays for the next one. */
const ACTIONS = {};

function wireActions(root) {
  delegate(root, 'click', '[data-action]', (e, el) => {
    const fn = ACTIONS[el.dataset.action];
    if (!fn) return;
    e.preventDefault();
    /* Pass the element through. Every handler here used to take no
       arguments, so this changes nothing for them — but a handler that
       needs to read a data- attribute off the button had no way to,
       and failed silently when it tried. */
    fn(el, e);
  });

  // The glossary filter: DOM-only, so typing never re-renders and
  // never writes.
  delegate(root, 'input', '[data-action="lib-gloss-filter"]', (e, el) => filterTerms(el));

  // A hit that lands on a term opens its card first, so the example is there.
  delegate(root, 'click', 'a[href*="#term-"]', (e, el) => {
    openTermFromHash((el.getAttribute('href') || '').split('#')[1]);
  });
  window.addEventListener('hashchange', () => openTermFromHash());
}

